/**
 * Bundles all scraped JSON files into a single TypeScript module.
 * Run after scrape-java-content.mjs finishes.
 *
 * Usage: node scripts/bundle-scraped-content.mjs
 * Output: src/data/generated/javaScrapedContent.ts
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SCRAPED_DIR = path.join(ROOT, "src/data/generated/scraped");
const OUTPUT_FILE = path.join(ROOT, "src/data/generated/javaScrapedContent.ts");
const INDEX_FILE = path.join(ROOT, "src/data/generated/javaScrapedIndex.json");

function main() {
  if (!fs.existsSync(SCRAPED_DIR)) {
    console.error("No scraped directory found. Run scrape-java-content.mjs first.");
    process.exit(1);
  }

  const files = fs.readdirSync(SCRAPED_DIR).filter(f => f.endsWith(".json"));
  console.log(`Bundling ${files.length} scraped files...`);

  const contentMap = {};
  let totalSections = 0;

  for (const file of files) {
    const topicId = file.replace(".json", "");
    try {
      const data = JSON.parse(fs.readFileSync(path.join(SCRAPED_DIR, file), "utf8"));
      // Store compact version - only what the renderer needs
      contentMap[topicId] = {
        title: data.title || topicId,
        source: data.source,
        url: data.url,
        sectionId: data.sectionId || "",
        sections: data.sections || [],
      };
      totalSections += (data.sections || []).length;
    } catch (e) {
      console.warn(`  Skipping ${file}: ${e.message}`);
    }
  }

  const ts = `// Auto-generated by scripts/bundle-scraped-content.mjs
// ${files.length} topics, ${totalSections} sections total
// DO NOT EDIT MANUALLY - run: node scripts/bundle-scraped-content.mjs

export type ScrapedSection = {
  heading: string;
  paragraphs: string[];
  code: string[];
};

export type ScrapedTopic = {
  title: string;
  source: string;
  url: string;
  sectionId: string;
  sections: ScrapedSection[];
};

export const javaScrapedContent: Record<string, ScrapedTopic> = ${JSON.stringify(contentMap, null, 2)} as const;

export function getScrapedTopic(topicId: string): ScrapedTopic | null {
  return (javaScrapedContent as Record<string, ScrapedTopic>)[topicId] ?? null;
}
`;

  fs.writeFileSync(OUTPUT_FILE, ts);
  console.log(`Written: ${OUTPUT_FILE}`);
  console.log(`Topics: ${files.length}, Sections: ${totalSections}`);
  const size = fs.statSync(OUTPUT_FILE).size;
  console.log(`File size: ${(size / 1024).toFixed(1)} KB`);

  // Also update the index
  const index = {
    generatedAt: new Date().toISOString(),
    topicCount: files.length,
    topics: Object.entries(contentMap).map(([id, t]) => ({
      id,
      title: t.title,
      sectionId: t.sectionId,
      source: t.source,
      sectionCount: t.sections.length,
    })),
  };
  fs.writeFileSync(INDEX_FILE, JSON.stringify(index, null, 2));
  console.log(`Index updated: ${INDEX_FILE}`);
}

main();
